#!/usr/bin/env node
// Builds the "add your own PDF" converter for the Godot web edition into <out>/import/:
//   holostudy-import.js   the study console's own scanner, copied at build time from engines/study/study.html
//                         (§02 ingest: PDF lines → headings → chapters → voice notes; §03 analytics: key terms,
//                         definitions, formulas, summary, recall quiz; §05b isSpeakable) — so an uploaded book is
//                         parsed exactly like the NCERT books — plus the Symbol-font map of tools/godot-content.mjs,
//                         the characters the app's fonts can draw (godot/assets/fonts/coverage.txt) and
//                         godot/web/import/driver.js (file picker, pdf.js, progress, holograms, MCQs, the API)
//   words.txt             the words of the NCERT books (godot/content/packs, 3+ uses each): tells glued words in a
//                         PDF's text from real ones (fetched only when a PDF is added)
//   pdf.min.js, pdf.worker.min.js   pdf.js 3.11 from vendor/ (loaded only when a PDF is added)
//   node tools/godot-import.mjs [out]        (default build/godot-web; tools/godot-build.mjs runs it)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// top-level declarations taken from the study console, in dependency order
const FROM_STUDY = ['clamp', 'hashStr', 'titleCase', 'SUBJECTS', 'STOP', 'CHAPTER_RE', 'NUMBERED_RE', 'FRONT_RE', 'NUMWORDS', 'splitSentences', 'wordCount',
  'textToBlocks', 'pdfToPages', 'joinLines', 'pdfOutlineChapters', 'clipOutline', 'cleanTitle', 'normaliseChapterTitle', 'romanToInt', 'buildChapters',
  'chapterWords', 'buildNotes', 'paginate', 'countRefs', 'detectSubject', 'GENERIC', 'Analytics', 'shuffle', 'isSpeakable'];
const FROM_CONTENT = ['SYMBOL', 'SYMBOL_HI', 'SYMBOL_PUA', 'fixChar'];

// a top-level `function name` / `const name =` runs until the next line that starts a new top-level statement
export function extract(src, names, from) {
  const lines = src.split('\n');
  const start = /^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=/;
  const top = /^(?:async\s+function|function|const|let|var|class|if|for|await|export|import|window\.|document\.)\b|^\/\/|^\/\*|^<\/?script/;
  const found = new Map();
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(start);
    const name = m && (m[1] || m[2]);
    if (!name || !names.includes(name) || found.has(name)) continue;
    let j = i + 1;
    while (j < lines.length && !top.test(lines[j])) j++;
    while (j > i + 1 && !lines[j - 1].trim()) j--;
    found.set(name, lines.slice(i, j).join('\n'));
  }
  const missing = names.filter((n) => !found.has(n));
  if (missing.length) throw new Error(`${from}: not found: ${missing.join(', ')} — the converter takes these from it; update FROM_* in tools/godot-import.mjs`);
  return names.map((n) => found.get(n)).join('\n');
}

export function bundle() {
  const study = fs.readFileSync(path.join(ROOT, 'engines', 'study', 'study.html'), 'utf8');
  const content = fs.readFileSync(path.join(ROOT, 'tools', 'godot-content.mjs'), 'utf8');
  const driver = fs.readFileSync(path.join(ROOT, 'godot', 'web', 'import', 'driver.js'), 'utf8');
  const covFile = path.join(ROOT, 'godot', 'assets', 'fonts', 'coverage.txt');
  const coverage = fs.existsSync(covFile) ? fs.readFileSync(covFile, 'utf8') : '';
  return `/* HoloStudy (Godot edition) — add your own PDF. Generated by tools/godot-import.mjs: do not edit; change
   engines/study/study.html (the scanner) or godot/web/import/driver.js (the rest). */
(() => {
'use strict';
const COVERAGE = ${JSON.stringify(coverage)};
// ─────────────── from engines/study/study.html ───────────────
${extract(study, FROM_STUDY, 'engines/study/study.html')}
// ─────────────── from tools/godot-content.mjs ───────────────
${extract(content, FROM_CONTENT, 'tools/godot-content.mjs')}
${driver}
})();
`;
}

export function words() {
  const dir = path.join(ROOT, 'godot', 'content', 'packs'), count = new Map();
  if (!fs.existsSync(dir)) return '';
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json'))) {
    const p = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    for (const c of p.chapters || []) for (const b of c.blocks || []) for (const w of String(b.t).toLowerCase().match(/[a-z]{2,}/g) || []) count.set(w, (count.get(w) || 0) + 1);
  }
  return [...count].filter(([, n]) => n >= 3).sort((a, b) => b[1] - a[1]).map(([w]) => w).join(' ');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const out = path.resolve(process.argv[2] || path.join(ROOT, 'build', 'godot-web'), 'import');
  fs.mkdirSync(out, { recursive: true });
  const js = bundle();
  new Function(js); // a syntax error fails the build here, not in a student's browser
  fs.writeFileSync(path.join(out, 'holostudy-import.js'), js);
  const list = words();
  fs.writeFileSync(path.join(out, 'words.txt'), list);
  for (const f of ['pdf.min.js', 'pdf.worker.min.js']) fs.copyFileSync(path.join(ROOT, 'vendor', 'cdnjs', 'ajax', 'libs', 'pdf.js', '3.11.174', f), path.join(out, f));
  console.log(`import: ${path.relative(ROOT, out)}/holostudy-import.js ${(js.length / 1024).toFixed(0)} KB, words.txt ${list ? list.split(' ').length : 0} words, pdf.js`);
}
